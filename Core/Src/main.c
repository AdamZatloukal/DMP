void init_game(uint8_t num_of_players){
	// Reset TIM7 values when a game begins
	last_toggle_time = 0;
	last_toggle = 0;
	last_toggle_end = 0;
	miliseconds = 0;
	last_toggle_overlap = 0;

	// Reset game stats values
	game_info.number_of_rolls = 0;
	game_info.number_of_set_pawns = 0;
	game_info.number_of_kicked_pawns = 0;

	init_brightness();
	game_info.number_of_players = num_of_players;
	init_board(num_of_players);

	game_info.current_player = 1;

	game_info.game_stage = IN_PROGRESS;
}

void handle_initialization(void){
	settings_animation();

	game_info.current_event = MENU;
}

void handle_in_progress(void){
	sync_info();	// Syncs up the selected pawn of the current player

	if(game_info.current_event == SELECT_PAWN){
		selected_pawn_animation(game_info.current_player);
	}

	if(game_info.current_event == PAWN_SELECTED){		// Executes when the selected_pawn is confirmed - once per player turn

		move_pawn(game_info.current_player, game_info.rolled_number);		// Also checks for kicks, finish, init

		game_info.current_event = ROLL_DICE;


		// If the player has already finished skip the player and check for player out of bounds
		while(select_player(game_info.current_player)->pawns_in_finish == 4){
			game_info.current_player++;
			game_info.current_player = game_info.current_player > game_info.number_of_players ? 1 : game_info.current_player;

			if(select_player(game_info.current_player)->pawns_in_finish != 4){
				game_info.selected_pawn = 0;
				return;
			}
		}

		// If the player rolled a 6 the player can play again
		if(game_info.rolled_number != 6){
			game_info.current_player++;
			game_info.current_player = game_info.current_player > game_info.number_of_players ? 1 : game_info.current_player;	// Checks if the turn has ended

			while(select_player(game_info.current_player)->pawns_in_finish == 4){
				game_info.current_player++;
				game_info.current_player = game_info.current_player > game_info.number_of_players ? 1 : game_info.current_player;
			}
		}
		game_info.selected_pawn = 0; // Probably useless
	}
}


void handle_finish(void){
	game_info.current_event = FINISH_GAME;
}

void set_player_color(void){
	Player* player_struct = select_player(1);

	player_struct->color[0] = 255;
	player_struct->color[1] = 0;
	player_struct->color[2] = 0;

	player_struct = select_player(2);

	player_struct->color[0] = 0;
	player_struct->color[1] = 0;
	player_struct->color[2] = 255;

	player_struct = select_player(3);

	player_struct->color[0] = 255;
	player_struct->color[1] = 255;
	player_struct->color[2] = 0;

	player_struct = select_player(4);

	player_struct->color[0] = 0;
	player_struct->color[1] = 255;
	player_struct->color[2] = 0;
}

